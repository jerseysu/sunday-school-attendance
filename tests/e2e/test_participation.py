"""Participation mode (家長陪同 / 獨立參與) and parent names: required on the sign-up page,
roster tag, add/edit dialog, and parent names surviving a teacher's phone edit."""
from playwright.sync_api import sync_playwright
from helpers import BASE, new_page, login, ok, rows, wait_until, call, shot, PIN

errs = []
mode_of = lambda name: next((r[7] if len(r) > 7 else "") for r in rows("孩子名單") if r[1] == name)

with sync_playwright() as p:
    b = p.chromium.launch()
    par = new_page(b, errs)
    par.goto(BASE + "/signup.html")
    par.wait_for_function("document.getElementById('consentText').textContent.includes('親愛的家長')")
    ok("家長和孩子一起在教室" in par.inner_text("#mode") and "家長仍須留在主堂或懇墾園" in par.inner_text("#mode"), "mode cards show their explanations")
    ok(par.locator("#mode[role=radiogroup] [role=radio]").count() == 2, "mode is a radio group with two cards")
    par.fill("#name", "陪同寶寶"); par.click("#group button[data-v='0-3']"); par.click("#rel button[data-v='爸爸']")
    par.fill("#phone", "0911-555-666"); par.click("#agreeConsent")
    par.click("#mode [data-v='陪同']")
    ok(par.is_disabled("#submit"), "submit disabled without a parent name")
    par.fill("#parentName", "張爸爸")
    ok(not par.is_disabled("#submit"), "submit enabled once the parent name is filled")
    par.fill("#parentName", "")
    ok(par.is_disabled("#submit"), "clearing the parent name disables submit again")
    par.fill("#parentName", "張爸爸")
    par.reload(); par.wait_for_function("document.getElementById('consentText').textContent.includes('親愛的家長')")
    par.fill("#name", "陪同寶寶"); par.click("#group button[data-v='0-3']"); par.click("#rel button[data-v='爸爸']")
    par.fill("#phone", "0911-555-666"); par.fill("#parentName", "張爸爸"); par.click("#agreeConsent")
    ok(par.is_disabled("#submit"), "submit disabled without a participation mode")
    par.focus("#mode [data-v='陪同']"); par.keyboard.press("ArrowDown")
    ok(par.get_attribute("#mode [data-v='獨立']", "aria-checked") == "true", "arrow keys move the radio selection")
    par.click("#mode [data-v='陪同']")
    ok(not par.is_disabled("#submit"), "submit enabled once a mode is chosen")
    ok("讓獨立在安全中發生" in par.inner_text("#form") and "送出時間會一併記錄" in par.inner_text("#form"), "thank-you line and consent-record note shown")
    shot(par, "participation-form.png")
    par.click("#submit"); par.wait_for_selector("#done", state="visible")
    ok(rows("報名待確認")[-1][12:14] == ["張爸爸", "陪同"], "sign-up stores parent name and mode")

    t = new_page(b, errs)
    login(t)
    # accept with the parent's choice (no change) → kid gets 陪同
    t.click("#signupBanner"); t.wait_for_selector("#sList [data-sid]")
    card = t.locator("#sList [data-sid]").first
    ok("爸爸 張爸爸" in card.inner_text() and "家長希望：家長陪同" in card.inner_text(), "pending card shows parent name and preferred mode")
    shot(t, "participation-card.png")
    card.locator("[data-scall]").click(); card.locator("[data-sok]").click()
    t.wait_for_selector("#sList .scard.ok")
    ok(mode_of("陪同寶寶") == "陪同", "accepting without changes keeps the parent's choice")
    t.click("#sClose")

    # teacher adds a child with 獨立參與
    t.click("#newBtn"); t.fill("#mName", "獨立寶寶")
    t.click("#mMode button[data-m='獨立']")
    ok(t.get_attribute("#mMode button[data-m='獨立']", "aria-pressed") == "true", "mode choice row in the add dialog")
    t.click("#mSave")
    wait_until(lambda: any(r[1] == "獨立寶寶" for r in rows("孩子名單")), msg="child added")
    ok(mode_of("獨立寶寶") == "獨立", "addKid saves the mode")
    t.click("#newBtn"); t.fill("#mName", "未定寶寶"); t.click("#mSave")
    wait_until(lambda: any(r[1] == "未定寶寶" for r in rows("孩子名單")), msg="child without mode added")

    t.click("#tab-list"); t.wait_for_selector("#kidList .row")
    row = lambda n: t.locator("#kidList .row", has_text=n)
    ok(row("獨立寶寶").locator(".pill.mode[data-m='獨立']").inner_text() == "獨立參與", "roster tags 獨立參與")
    ok(row("陪同寶寶").locator(".pill.mode[data-m='陪同']").inner_text() == "家長陪同", "roster tags 家長陪同")
    ok(row("未定寶寶").locator(".pill.mode").count() == 0, "no tag when mode is not set")
    t.wait_for_selector(".phone .pname")
    ok("張爸爸" in row("陪同寶寶").inner_text(), "roster shows the parent's name next to the relation")
    shot(t, "participation-roster.png")

    # edit dialog: change mode, then clear it by tapping the selected one
    row("獨立寶寶").locator("button.btn[data-edit]").click()
    ok(t.get_attribute("#mMode button[data-m='獨立']", "aria-pressed") == "true", "edit dialog shows the saved mode")
    t.click("#mMode button[data-m='陪同']"); t.click("#mSave")
    wait_until(lambda: mode_of("獨立寶寶") == "陪同", msg="mode changed to 陪同")
    ok(row("獨立寶寶").locator(".pill.mode[data-m='陪同']").count() == 1, "roster tag follows the edit")
    row("獨立寶寶").locator("button.btn[data-edit]").click()
    t.click("#mMode button[data-m='陪同']")
    ok(t.locator("#mMode button[aria-pressed=true]").count() == 0, "tapping the selected mode clears it")
    t.click("#mSave")
    wait_until(lambda: mode_of("獨立寶寶") == "", msg="mode cleared")
    ok(row("獨立寶寶").locator(".pill.mode").count() == 0, "tag disappears when the mode is cleared")

    # parent name survives a teacher's phone edit (setContacts rewrites the whole list)
    row("陪同寶寶").locator("button.btn[data-edit]").click(); t.wait_for_selector("#mPhone0")
    ok("家長姓名：張爸爸" in t.inner_text("#mContacts"), "edit dialog shows the parent's name read-only")
    shot(t, "participation-edit.png")
    t.fill("#mPhone0", "0911-777-888")
    t.click("#mAddParent"); t.click("[data-ci='1'][data-rel='媽媽']"); t.fill("#mPhone1", "0922-000-111")
    t.click("#mSave")
    wait_until(lambda: len([r for r in rows("家長聯絡") if r[1] == "陪同寶寶"]) == 2, msg="phones saved")
    got = sorted((r[2], r[3], r[6]) for r in rows("家長聯絡") if r[1] == "陪同寶寶")
    ok(got == [("媽媽", "0922-000-111", ""), ("爸爸", "0911-777-888", "張爸爸")], "parent name kept after the phone change; new parent has none")
    kid = next(r[0] for r in rows("孩子名單") if r[1] == "陪同寶寶")
    ok(sorted((c["rel"], c["name"]) for c in call("getContacts", kid, pin=PIN)["data"]) == [("媽媽", ""), ("爸爸", "張爸爸")], "getContacts returns parent names")
    ok(mode_of("陪同寶寶") == "陪同", "editing phones leaves the mode alone")
    ok(not errs, f"no page errors: {errs}")
    b.close()
